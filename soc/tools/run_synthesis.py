#!/usr/bin/env python3
"""Run reproducible generic Yosys synthesis, preserving memory arrays."""
import argparse
from collections import Counter
from functools import lru_cache
from hashlib import sha256
import json
from pathlib import Path
import re
import shutil
import subprocess
import sys
import time

ROOT = Path(__file__).resolve().parents[2]
IDENTIFIER = re.compile(r'^[A-Za-z_][A-Za-z0-9_$]*$')
DEFINE = re.compile(r'^[A-Za-z_][A-Za-z0-9_]*(?:=[A-Za-z0-9_]+)?$')


def quote(value):
    value = str(value)
    if any(char in value for char in '\r\n\x00'):
        raise ValueError('newline/NUL is not allowed in Yosys arguments')
    return '"' + value.replace('\\', '\\\\').replace('"', '\\"') + '"'


def integer(value):
    if isinstance(value, int):
        return value
    return int(value, 2)


def resources(netlist, top):
    """Count physical occurrences through hierarchy, not just unique modules."""
    modules = netlist['modules']

    @lru_cache(None)
    def walk(name):
        counts = Counter()
        arrays = bits = registers = processes = 0
        module = modules[name]
        processes += len(module.get('processes', {}))
        for cell in module.get('cells', {}).values():
            kind = cell['type']
            if kind in modules and not integer(modules[kind].get('attributes', {}).get('blackbox', 0)):
                child, child_arrays, child_bits, child_registers, child_processes = walk(kind)
                counts.update(child)
                arrays += child_arrays
                bits += child_bits
                registers += child_registers
                processes += child_processes
            else:
                counts[kind] += 1
                parameters = cell.get('parameters', {})
                if kind in ('$mem_v2', '$mem'):
                    arrays += 1
                    bits += integer(parameters['WIDTH']) * integer(parameters['SIZE'])
                elif kind.startswith(('$_DFF', '$_SDFF', '$_ADFF')):
                    registers += 1
                elif kind.startswith(('$dff', '$sdff', '$adff', '$aldff')):
                    registers += integer(parameters['WIDTH'])
        return counts, arrays, bits, registers, processes

    cells, arrays, bits, registers, processes = walk(top)
    return {'leaf_cells': sum(cells.values()), 'cells_by_type': dict(sorted(cells.items())),
            'memory_arrays': arrays, 'memory_bits': bits, 'register_bits': registers,
            'processes_remaining': processes,
            'latch_cells': sum(count for kind, count in cells.items() if 'latch' in kind.lower())}


def find_yosys(explicit):
    if explicit:
        path = shutil.which(explicit)
        if path:
            return path
        if Path(explicit).is_file():
            return str(Path(explicit).resolve())
        raise ValueError('Yosys executable not found: ' + explicit)
    path = Path.home() / '.local/share/tinysoc-synth/venv/bin/yowasp-yosys'
    if path.is_file():
        return str(path)
    for name in ['yosys', 'yowasp-yosys']:
        path = shutil.which(name)
        if path:
            return path
    raise ValueError('Yosys not found. Run soc/scripts/setup_synth_env.sh or pass --yosys.')


def load_profile(path, name, override):
    profiles = json.loads(path.read_text(encoding='utf-8'))
    if name not in profiles:
        raise ValueError('unknown profile %r; choices: %s' % (name, ', '.join(profiles)))
    profile = dict(profiles[name])
    profile['top'] = override or profile['top']
    if not IDENTIFIER.fullmatch(profile['top']):
        raise ValueError('invalid top module identifier')
    sources = [(ROOT / source).resolve() for source in profile['sources']]
    if not sources:
        raise ValueError('a synthesis profile must contain source files')
    simulation_models = (ROOT / 'soc/sim/models').resolve()
    for source in sources:
        if not source.is_file():
            raise ValueError('missing synthesis source: ' + str(source))
        if simulation_models in source.parents:
            raise ValueError('functional simulation substitutes are not synthesis inputs: ' + str(source))
    defines = profile.get('defines', [])
    if not all(DEFINE.fullmatch(item) for item in defines):
        raise ValueError('invalid preprocessor definition')
    if 'SYNTHESIS' not in defines:
        raise ValueError('profiles must explicitly define SYNTHESIS')
    return profile, sources


def script(profile, sources, output, stage):
    commands = ['# Generated by soc/tools/run_synthesis.py. Memory arrays are preserved.']
    flags = ' '.join('-D' + define for define in profile['defines'])
    for source in sources:
        commands.append('read_verilog -sv %s %s' % (flags, quote(source)))
    # Explicit passes avoid version-dependent synth -run endpoint semantics.
    commands += ['hierarchy -check -top ' + profile['top'], 'chformal -remove', 'proc', 'opt', 'fsm', 'opt',
                 'wreduce', 'peepopt', 'opt_clean', 'alumacc', 'share', 'opt',
                 'memory -nomap', 'opt_clean']
    if stage == 'gates':
        # Do not run memory_map: millions of SRAM bits must not become DFF banks.
        commands += ['techmap', 'opt', 'abc -g simple -script "+strash; map"', 'opt_clean']
    # Run in the build directory. Older Yosys tee does not unquote -o paths.
    # Fixed relative filenames also make replay independent of the old output path.
    commands += ['check -assert',
                 'tee -o stat.json stat -json -top ' + profile['top'],
                 'write_json netlist.json',
                 'write_verilog -noattr netlist.v']
    return '\n'.join(commands) + '\n'


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--profile', default='vta-local')
    parser.add_argument('--profiles', type=Path, default=ROOT / 'soc/synth/profiles.json')
    parser.add_argument('--top', help='override the selected top without editing RTL')
    parser.add_argument('--stage', choices=['coarse', 'gates'], default='coarse')
    parser.add_argument('--yosys', help='native yosys or yowasp-yosys executable')
    parser.add_argument('--build-dir', type=Path)
    parser.add_argument('--timeout', type=int, default=600, help='synthesis runtime limit, seconds')
    args = parser.parse_args()
    started = time.monotonic()
    output = None
    summary = None
    try:
        profile, sources = load_profile(args.profiles, args.profile, args.top)
        yosys = find_yosys(args.yosys)
        output = (args.build_dir or ROOT / 'soc/build/synthesis' / args.profile / args.stage).resolve()
        output.mkdir(parents=True, exist_ok=True)
        # Invalidate only named build products so a failed run cannot look successful.
        for name in ['netlist.json', 'netlist.v', 'stat.json', 'report.md', 'summary.json']:
            (output / name).unlink(missing_ok=True)
        summary = {'status': 'running', 'profile': args.profile, 'top': profile['top'], 'stage': args.stage,
                   'scope': profile.get('description', ''), 'yosys': None, 'executable': yosys,
                   'memory_policy': 'preserve arrays; no physical SRAM/BRAM mapping',
                   'verification_policy': 'remove formal/assertion cells from synthesis only',
                   'defines': profile['defines'], 'sources': [
                       {'path': str(source), 'sha256': sha256(source.read_bytes()).hexdigest()} for source in sources]}
        (output / 'summary.json').write_text(json.dumps(summary, indent=2) + '\n', encoding='utf-8')
        version = subprocess.run([yosys, '-V'], capture_output=True, text=True, check=True, timeout=60).stdout.strip()
        summary['yosys'] = version
        ys = output / 'run.ys'
        ys.write_text(script(profile, sources, output, args.stage), encoding='utf-8')
        print('Synthesizing %s (%s), memories preserved...' % (profile['top'], args.stage), flush=True)
        with (output / 'console.log').open('w', encoding='utf-8') as console:
            result = subprocess.run([yosys, '-Q', '-T', '-q', '-l', str(output / 'yosys.log'), '-s', str(ys)],
                                    cwd=output, stdout=console, stderr=subprocess.STDOUT, timeout=args.timeout)
        if result.returncode:
            raise RuntimeError('Yosys exited with code %d; see %s' % (result.returncode, output / 'console.log'))
        metrics = resources(json.loads((output / 'netlist.json').read_text()), profile['top'])
        if metrics['processes_remaining']:
            raise RuntimeError('synthesis left unlowered RTL processes')
        warnings = sorted(set(line.strip() for line in (output / 'yosys.log').read_text().splitlines() if line.startswith('Warning:')))
        summary.update(status='passed', elapsed_seconds=round(time.monotonic() - started, 3),
                       structural_check='check -assert passed', warnings=warnings, resources=metrics)
        report = '''# TinySoC generic synthesis report

- Top: `{top}`; profile: `{profile}`; stage: `{stage}`.
- Tool: {version}.
- Scope: {scope}
- Structural check: `check -assert` passed; no RTL processes remain.
- Hierarchical leaf cells: {cells}; register bits: {registers}; latch cells: {latches}.
- Preserved memory arrays: {arrays}; memory bits: {bits} ({kib:.3f} KiB).
- Unique warning messages: {warnings}.

`coarse` retains word-level arithmetic. `gates` additionally maps logic through
techmap/ABC into generic gates. Both preserve RAM arrays and are independent of
an ASIC standard-cell library or an FPGA device.
Verification-only assertion cells are removed from the synthesis view.

These counts are not ASIC area, FPGA LUT/BRAM utilization, timing closure, Fmax,
power, or a whole-SoC synthesis result. Physical mapping requires a separate
target profile and its technology/board inputs. Simulation SRAM substitutes are
not included.

Inputs and hashes: `summary.json`. Detailed statistics: `stat.json`.
Netlists: `netlist.v`, `netlist.json`. Reproduction script: `run.ys`.
'''.format(top=profile['top'], profile=args.profile, stage=args.stage, version=version,
           scope=profile.get('description', ''), cells=metrics['leaf_cells'], registers=metrics['register_bits'],
           latches=metrics['latch_cells'], arrays=metrics['memory_arrays'], bits=metrics['memory_bits'],
           kib=metrics['memory_bits'] / 8192, warnings=len(warnings))
        (output / 'report.md').write_text(report, encoding='utf-8')
        (output / 'summary.json').write_text(json.dumps(summary, indent=2) + '\n', encoding='utf-8')
        print('PASS: %d leaf cells, %d memory arrays (%d bits), %d register bits' % (
            metrics['leaf_cells'], metrics['memory_arrays'], metrics['memory_bits'], metrics['register_bits']))
        print('Report:', output / 'report.md')
        return 0
    except (OSError, ValueError, KeyError, RuntimeError, subprocess.SubprocessError) as error:
        if summary is not None:
            summary.update(status='failed', error=str(error), elapsed_seconds=round(time.monotonic() - started, 3))
            (output / 'summary.json').write_text(json.dumps(summary, indent=2) + '\n', encoding='utf-8')
        print('error:', error, file=sys.stderr)
        return 1


if __name__ == '__main__':
    sys.exit(main())
